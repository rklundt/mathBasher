import { describe, expect, it } from 'vitest';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import sharp from 'sharp';
import { ALIEN_SHIP_SHEET, SPRITE_MANIFEST, SpaceShooterSpriteKeys, spritePath } from '@/core/spriteKeys';
import { AUDIO_MANIFEST, GAME_MIDGROUND_MAP, GAME_MUSIC_MAP } from '@/core/audioKeys';

/**
 * Sprint 2.6 — Space Shooter's ship sheet is generated by
 * `scripts/sprites/alienships.mjs` and the scenery by `cockpit.mjs`; the
 * geometry the game uses lives in `spriteKeys.ts`. Guards the two against
 * drifting apart, and checks every game-scoped file is on disk.
 */
const PUBLIC = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'public');
const onDisk = (url: string): string => resolve(PUBLIC, url.replace(/^\//, ''));

describe('Space Shooter assets', () => {
  it('the ship sheet holds every ship at the declared frame size', async () => {
    const s = ALIEN_SHIP_SHEET;
    const meta = await sharp(onDisk(spritePath('hero', s.key))).metadata();
    expect(meta.width).toBe(s.frame * s.cols);
    expect(meta.height).toBe(s.frame * s.rows);
    expect(s.cols * s.rows).toBe(s.count);
    // The porthole sits inside the frame.
    expect(s.porthole.x - s.porthole.r).toBeGreaterThan(0);
    expect(s.porthole.y + s.porthole.r).toBeLessThan(s.frame);
  });

  it('the cosmos fills the 16:9 canvas and the cockpit is 16:9 too', async () => {
    const cosmos = await sharp(onDisk(spritePath('bg', SpaceShooterSpriteKeys.Cosmos))).metadata();
    expect([cosmos.width, cosmos.height]).toEqual([1280, 720]);
    const cockpit = await sharp(onDisk(spritePath('hero', SpaceShooterSpriteKeys.Cockpit))).metadata();
    expect(cockpit.width! / cockpit.height!).toBeCloseTo(16 / 9, 2);
    expect(cockpit.hasAlpha).toBe(true);
  });

  it('every game:space-shooter sprite exists', () => {
    const sprites = SPRITE_MANIFEST.filter((e) => e.scope === 'game:space-shooter');
    expect(sprites.map((e) => e.key).sort()).toEqual(['alien-ships', 'cockpit', 'space-cosmos']);
    for (const e of sprites) expect(existsSync(onDisk(e.url)), e.url).toBe(true);
  });

  it('plays its own music (no ambience) and the music file exists', () => {
    expect(GAME_MUSIC_MAP['space-shooter']).toBe('loop-7');
    expect(GAME_MIDGROUND_MAP['space-shooter']).toEqual([]);
    const audio = AUDIO_MANIFEST.filter((e) => e.scope === 'game:space-shooter');
    expect(audio.map((e) => e.key)).toEqual(['loop-7']);
    for (const e of audio) expect(existsSync(onDisk(e.url)), e.url).toBe(true);
  });

  it('reuses Alien Shoot effects, which load with the menus', () => {
    for (const key of ['fire-1', 'fire-2', 'hit-correct-1', 'hit-wrong-1', 'timeout-fail-1']) {
      expect(AUDIO_MANIFEST.find((e) => e.key === key)?.scope, key).toBe('eager');
    }
  });
});
