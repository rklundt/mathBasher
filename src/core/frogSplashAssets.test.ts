import { describe, expect, it } from 'vitest';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import sharp from 'sharp';
import {
  FLY_SHEET,
  FROG_POSE_COUNT,
  FROG_SHEET,
  FrogSpriteKeys,
  PondSpriteKeys,
  SPLASH_SHEET,
  SPRITE_MANIFEST,
  spritePath,
} from '@/core/spriteKeys';
import { config } from '@/core/config';
import { AUDIO_MANIFEST, GAME_MIDGROUND_MAP, GAME_MUSIC_MAP, audioGainFor } from '@/core/audioKeys';

/**
 * Sprint 2.5.6 — Frog Splash's sheets are generated by
 * `scripts/sprites/{frog,pond}.mjs`; the frame geometry the game slices
 * them with lives in `spriteKeys.ts`. Guards the two against drifting
 * apart, and checks every game-scoped file is on disk.
 */
const PUBLIC = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'public');
const onDisk = (url: string): string => resolve(PUBLIC, url.replace(/^\//, ''));

describe('Frog Splash assets', () => {
  it('frog sheets hold every pose at the declared frame size', async () => {
    for (const key of Object.values(FrogSpriteKeys)) {
      const meta = await sharp(onDisk(spritePath('hero', key))).metadata();
      expect(meta.height).toBe(FROG_SHEET.frame);
      expect(meta.width).toBe(FROG_SHEET.frame * FROG_POSE_COUNT);
    }
  });

  it('bank images are as tall as the river layout expects', async () => {
    for (const key of [PondSpriteKeys.BankNear, PondSpriteKeys.BankFar]) {
      const meta = await sharp(onDisk(spritePath('bg', key))).metadata();
      expect(meta.height, key).toBe(config.frogSplash.bankHeightPx);
      expect(meta.width, key).toBe(1280);
    }
  });

  it('fly and splash sheets match their declared geometry', async () => {
    for (const [kind, s] of [
      ['hero', FLY_SHEET],
      ['bg', SPLASH_SHEET],
    ] as const) {
      const meta = await sharp(onDisk(spritePath(kind, s.key))).metadata();
      expect(meta.height).toBe(s.frameHeight);
      expect(meta.width).toBe(s.frameWidth * s.frames);
    }
  });

  it('every game:frog-splash sprite exists', () => {
    const sprites = SPRITE_MANIFEST.filter((e) => e.scope === 'game:frog-splash');
    expect(sprites.length).toBeGreaterThan(0);
    for (const e of sprites) expect(existsSync(onDisk(e.url)), e.url).toBe(true);
  });

  it('every game:frog-splash sound exists', () => {
    const audio = AUDIO_MANIFEST.filter((e) => e.scope === 'game:frog-splash');
    expect(audio.map((e) => e.key).sort()).toEqual(
      [
        'frog-hop-1',
        'frog-hop-2',
        'frog-hop-3',
        'frog-hop-4',
        'frog-ribbit-1',
        'frog-ribbit-2',
        'frog-ribbit-3',
        'frog-ribbit-4',
        'frog-slurp-1',
        'frog-slurp-2',
        'frog-splash-1',
        'frog-splash-2',
        'frog-splash-3',
        'river-brook-1',
        'river-crickets-1',
        'loop-6',
      ].sort(),
    );
    for (const e of audio) expect(existsSync(onDisk(e.url)), e.url).toBe(true);
  });

  it('layers the brook and crickets, with the crickets well below the brook', () => {
    expect(GAME_MIDGROUND_MAP['frog-splash']).toEqual(['river-brook-1', 'river-crickets-1']);
    const brookDb = 20 * Math.log10(audioGainFor('river-brook-1'));
    const cricketsDb = 20 * Math.log10(audioGainFor('river-crickets-1'));
    expect(brookDb - cricketsDb).toBeGreaterThanOrEqual(6);
  });

  it('mixes the music under the brook', () => {
    expect(GAME_MUSIC_MAP['frog-splash']).toBe('loop-6');
    expect(audioGainFor('loop-6')).toBeLessThan(audioGainFor('river-brook-1'));
  });
});
