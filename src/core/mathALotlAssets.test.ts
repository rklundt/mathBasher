import { describe, expect, it } from 'vitest';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import sharp from 'sharp';
import { AXOLOTL_SHEET, AxolotlSpriteKeys, REEF_SHEETS, SPRITE_MANIFEST, spritePath } from '@/core/spriteKeys';
import { AUDIO_MANIFEST, GAME_MIDGROUND_MAP, GAME_MUSIC_MAP, audioGainFor } from '@/core/audioKeys';

/**
 * Sprint 2.5.4 — Math-a-lotl's sprite sheets are generated by
 * `scripts/sprites/{axolotl,reef}.mjs`; the frame geometry the game
 * slices them with lives in `spriteKeys.ts`. This guards the two
 * against drifting apart (a wrong frameWidth slices the sheet into
 * garbage frames) and checks every game-scoped asset is on disk.
 */
const PUBLIC = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'public');
const onDisk = (url: string): string => resolve(PUBLIC, url.replace(/^\//, ''));

describe('Math-a-lotl assets', () => {
  it('axolotl sheets are swimFrames + 1 happy frame wide at the declared frame size', async () => {
    for (const key of Object.values(AxolotlSpriteKeys)) {
      const meta = await sharp(onDisk(spritePath('hero', key))).metadata();
      expect(meta.height).toBe(AXOLOTL_SHEET.frameHeight);
      expect(meta.width).toBe(AXOLOTL_SHEET.frameWidth * (AXOLOTL_SHEET.swimFrames + 1));
      expect(AXOLOTL_SHEET.happyFrame).toBe(AXOLOTL_SHEET.swimFrames);
    }
  });

  it('reef sheets match their declared frame geometry', async () => {
    for (const [key, geo] of Object.entries(REEF_SHEETS)) {
      const meta = await sharp(onDisk(spritePath('bg', key))).metadata();
      expect(meta.height).toBe(geo.frameHeight);
      expect(meta.width).toBe(geo.frameWidth * geo.frames);
    }
  });

  it('every game:math-a-lotl sprite and audio file exists', () => {
    const sprites = SPRITE_MANIFEST.filter((e) => e.scope === 'game:math-a-lotl');
    const audio = AUDIO_MANIFEST.filter((e) => e.scope === 'game:math-a-lotl');
    expect(sprites.length).toBeGreaterThan(0);
    expect(audio.length).toBeGreaterThan(0);
    for (const e of [...sprites, ...audio]) expect(existsSync(onDisk(e.url)), e.url).toBe(true);
  });

  it('mixes the music below the water ambience', () => {
    const music = audioGainFor(GAME_MUSIC_MAP['math-a-lotl']);
    const ambience = GAME_MIDGROUND_MAP['math-a-lotl'].map(audioGainFor);
    expect(ambience).toHaveLength(2);
    for (const g of ambience) expect(music).toBeLessThan(g);
  });

  it('plays a wrong catch louder than a right one', () => {
    // Both sets are sfx normalized to the same target, but the pops
    // measure ~4 dB hotter; the gain must more than cancel that.
    const popDb = 20 * Math.log10(audioGainFor('bubble-pop-1'));
    const wrongDb = 20 * Math.log10(audioGainFor('bubble-wrong-1'));
    const MEASURED_POP_HEADROOM_DB = 4;
    expect(wrongDb - (popDb + MEASURED_POP_HEADROOM_DB)).toBeGreaterThan(0);
  });

  it('unlisted keys play at full gain', () => {
    expect(audioGainFor('hit-correct-1')).toBe(1);
  });
});
